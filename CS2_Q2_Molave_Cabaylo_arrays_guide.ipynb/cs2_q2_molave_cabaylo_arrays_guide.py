def display_scores(scores):
    """Displays the list of student scores in a clear, organized format."""
    print("\n--- Current Student Scores ---")
    if not scores:
        print("No scores available.")
    else:
        for i, score in enumerate(scores, start=1):
            print(f"Student {i}: {score}")
        print("-" * 28)

def search_score(scores):
    """Searches for a specific score value within the array/list."""
    print("\n--- Search Score ---")
    try:
        target = float(input("Enter the score you want to search for: "))
        if target in scores:
            # Find all 1-based positions where the score occurs
            positions = [i for i, score in enumerate(scores, start=1) if score == target]
            print(f"Success! Score {target} found at Student position(s): {positions}")
        else:
            print(f"Score {target} was not found in the list.")
    except ValueError:
        print("Invalid input. Please enter a numeric score.")

def compute_average(scores):
    """Computes and displays the sum and average of the scores."""
    print("\n--- Compute Average Score ---")
    if not scores:
        print("No scores available to compute average.")
        return

    total = sum(scores)
    count = len(scores)
    average = total / count

    print(f"Total Accumulated Score: {total}")
    print(f"Total Number of Students: {count}")
    print(f"Class Average Score: {average:.2f}")

def update_score(scores):
    """Updates a specific value in the list using its index."""
    print("\n--- Update Score ---")
    display_scores(scores)

    try:
        choice = int(input("Enter the student number (index) you want to update: "))
        if 1 <= choice <= len(scores):
            old_score = scores[choice - 1]
            new_score = float(input(f"Enter the new score for Student {choice} (Current: {old_score}): "))

            # Update using 0-based indexing
            scores[choice - 1] = new_score
            print(f"Successfully updated Student {choice} from {old_score} to {new_score}!")
        else:
            print("Error: Invalid student number selected.")
    except ValueError:
        print("Invalid input. Please enter valid numbers.")

# Initial list of scores stored in an array/list
scores = [85, 92, 78, 95, 88, 76, 90]

while True:
    print("\n=== Student Score Analyzer ===")
    print("Select the number of the operation you want to perform:")
    print("1. Display Scores")
    print("2. Search Score")
    print("3. Compute Average Score")
    print("4. Update Score")
    print("5. Display Updated Scores")
    print("6. Exit")

    choice = input("\nEnter your choice: ").strip()

    if choice == '1':
        display_scores(scores)
    elif choice == '2':
        search_score(scores)
    elif choice == '3':
        compute_average(scores)
    elif choice == '4':
        update_score(scores)
    elif choice == '5':
        display_scores(scores)
    elif choice == '6':
        print("\nExiting program. Thank you!")
        break
    else:
        print("\nInvalid choice! Please enter a number between 1 and 6.")

