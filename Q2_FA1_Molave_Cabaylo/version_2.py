# Returns (sum, difference, product, quotient)
def calculate(num1, num2):
    total = num1 + num2
    difference = num1 - num2
    product = num1 * num2
    # Guard against division by zero
    quotient = num1 / num2 if num2 != 0 else "Cannot divide by zero."
    return total, difference, product, quotient


# Inputs (float() allows decimals)
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

# Unpack the four returned values
total, difference, product, quotient = calculate(num1, num2)

# Output
print("Sum:", total)
print("Difference:", difference)
print("Product:", product)
print("Quotient:", quotient)

